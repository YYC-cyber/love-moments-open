def _ingredients(spec: DishSpec) -> list[dict[str, Any]]:
    result = []
    existing = set()
    seasonings = RECIPE_SEASONING_PROFILES.get(spec.slug, SEASONING_PROFILES[spec.technique])
    profile = {name: (quantity, unit) for name, quantity, unit in seasonings}
    amount_overrides = RECIPE_INGREDIENT_AMOUNTS.get(spec.slug, {})
    for name in spec.ingredients:
        quantity, unit = amount_overrides.get(name, profile.get(name, _amount(name)))
        is_seasoning = name in profile or name in AROMATIC_NAMES
        result.append({
            "name": name,
            "quantity": quantity,
            "unit": unit,
            "group": "seasoning" if is_seasoning else "main",
            "preparation": "按配方量称好并单独放置，避免下锅时漏放或重复放" if is_seasoning else _preparation(name),
        })
        existing.add(name)
    for name, quantity, unit in seasonings:
        if name in existing:
            continue
        group = "main" if name in PROFILE_MAIN_NAMES else "seasoning"
        preparation = _preparation(name) if group == "main" else "按配方量称好并单独放置，避免下锅时漏放或重复放"
        result.append({"name": name, "quantity": quantity, "unit": unit, "group": group, "preparation": preparation})
    return result


def _join(names: tuple[str, ...]) -> str:
    return "、".join(names)


