def validate_expansion_recipe(recipe: dict[str, Any], slug: str) -> None:
    """Validate one completed expansion recipe and raise on unsafe output."""

    for item in recipe["ingredients"]:
        if item["unit"] == "克" and item["name"] in CONCENTRATED_MAX_GRAMS:
            maximum = CONCENTRATED_MAX_GRAMS[item["name"]]
            if float(item["quantity"]) > maximum:
                raise ValueError(f"{recipe['name']} 的 {item['name']} 超过审核上限 {maximum} 克")
    text = "".join(
        str(step.get(field, ""))
        for step in recipe["steps"]
        for field in ("title", "instruction", "heat_level", "key_point")
    )
    text += "".join(str(item.get("preparation", "")) for item in recipe["ingredients"])
    for choices in SEMANTIC_REQUIREMENTS.get(slug, ()):
        if not any(word in text for word in choices):
            raise ValueError(f"{recipe['name']} 缺少关键工艺：{'/'.join(choices)}")


def audit_normalized_catalog(recipes: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Audit every normalized built-in recipe; raise with its exact name on failure."""

    reports: list[dict[str, Any]] = []
    wait_words = ("浸泡", "泡软", "静置", "醒发", "发酵", "冷藏", "冷却", "腌", "放凉", "吐沙")
    ambiguous = (
        "或水开后上锅蒸制", "蒸制或中火浸煮",
        "烤箱提前预热至180～210℃；煎制菜肴", "取适量", "倒入适量",
        "需要去腥时", "素食材则", "焯水、炒香或冲洗", "彻底煮熟或煎熟",
        "复炸或熬汁", "拌面捞出后快速过温水并沥干；汤面则",
    )
    for recipe in recipes:
        problems: list[str] = []
        ingredients = recipe.get("ingredients", [])
        ingredient_names = {str(item.get("name", "")) for item in ingredients}
        if len(ingredient_names) != len(ingredients):
            problems.append("存在重复食材")
        text = "".join(
            str(step.get(field, ""))
            for step in recipe.get("steps", [])
            for field in ("title", "instruction", "heat_level", "key_point")
        )
        text += "".join(str(item.get("preparation", "")) for item in ingredients)
        if any(value in text for value in ambiguous):
            problems.append("步骤仍包含不确定的二选一做法")
        if recipe.get("passive_minutes", 0) and not any(word in text for word in wait_words):
            problems.append("等待时间没有对应步骤")
        if ingredient_names and not any(name in text for name in ingredient_names):
            problems.append("步骤没有引用任何实际食材")
        if not any("室温" in tip and "2小时" in tip for tip in recipe.get("tips", [])):
            problems.append("缺少易腐食物保存提示")
        expected_safety = safety_tip(ingredient_names)
        safety_lines = [tip for tip in recipe.get("tips", []) if "食品安全" in tip]
        if expected_safety and expected_safety not in safety_lines:
            problems.append("安全中心温度与食材不匹配")
        if not expected_safety and safety_lines:
            problems.append("出现与食材不匹配的安全温度")
        if recipe.get("allergen_tags", []) != inferred_allergens(ingredient_names):
            problems.append("过敏原未按实际配料统一推导")
        for item in ingredients:
            name = str(item.get("name", ""))
            quantity = int(item.get("quantity_milli") or 0) / 1000
            unit = item.get("canonical_unit")
            if quantity <= 0:
                problems.append(f"{name} 缺少正数用量")
            elif (unit == "g" and quantity > 2000) or (unit == "ml" and quantity > 5000) or (unit == "piece" and quantity > 60):
                problems.append(f"{name} 用量超出家庭菜谱合理边界")
            if name in CONCENTRATED_MAX_GRAMS and item.get("canonical_unit") == "g":
                grams = quantity
                if grams > CONCENTRATED_MAX_GRAMS[name]:
                    problems.append(f"{name} {grams:g}克超过上限")
        if problems:
            raise ValueError(f"{recipe.get('name', recipe.get('id', '未知菜谱'))} 未通过内容审核：{'；'.join(problems)}")
        reports.append({
            "id": recipe["id"],
            "name": recipe["name"],
            "status": "passed",
            "checks": ("用量", "步骤匹配", "火力计时", "完成判断", "等待时间", "食品安全", "过敏原"),
        })
    return reports
