def build_expansion_recipes() -> list[dict[str, Any]]:
    """Return complete v2 recipe payloads for the offline expansion pack."""

    result: list[dict[str, Any]] = []
    for spec in DISHES:
        prep_minutes, cook_minutes, passive_minutes, difficulty = timing_for(spec.slug, PROFILE_TIMES[spec.technique])
        slots = ["breakfast", "snack"] if spec.category in {"早餐", "烘焙"} else ["lunch", "dinner"]
        seasonings = RECIPE_SEASONING_PROFILES.get(spec.slug, SEASONING_PROFILES[spec.technique])
        ingredient_names = set(spec.ingredients) | {name for name, _, _ in seasonings}
        tips = [
            "调料按两人份给出，可在起锅前尝味后小幅调整；首次制作不要一次额外加盐。",
            "易腐食物在室温放置不要超过2小时；剩余食物应及时分装冷藏。",
        ]
        safe = safety_tip(ingredient_names)
        if safe:
            tips.append(safe)
        value = {
            "id": f"recipe_builtin_exp_{spec.slug}",
            # Bump whenever deterministic quantities or steps change so an
            # existing installation refreshes the built-in catalog on start.
            "version": 9,
            "name": spec.name,
            "cuisine": spec.cuisine,
            "category": spec.category,
            "meal_slots": slots,
            "base_servings": 2,
            "prep_minutes": prep_minutes,
            "cook_minutes": cook_minutes,
            "passive_minutes": passive_minutes,
            "difficulty": difficulty,
            "ingredients": _ingredients(spec),
            "steps": _steps(spec, seasonings),
            "tips": tips,
            "allergen_tags": _allergens(spec, seasonings),
        }
        validate_expansion_recipe(value, spec.slug)
        result.append(value)
    return result
